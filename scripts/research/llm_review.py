"""Run one structured hostile review against the built manuscript.

This intentionally does NOT call an LLM API on this box (no credential is
configured for a review model in this environment, and the plan is explicit
that the reviewer must be independent of the writer's own reasoning - it
should not run with this session's context). Instead it packages every
input the plan specifies (manuscript text, refcheck output, literature
candidates, results.tex) into one bundle and prints instructions for
running the actual review as an isolated subagent with no access to this
session's context, exactly as already done once for this manuscript
(see log/ for the review that found the tail6 cost-claim contamination).

llm_review_gate.py then reads that subagent's JSON verdict and enforces the
BLOCKER/MAJOR -> FAIL policy. This script only assembles the bundle.
"""

import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BUNDLE_PATH = os.path.join(REPO, "build", "research", "review-bundle.json")

REVIEWER_PROMPT = """\
Act as a hostile academic reviewer looking specifically for rejection
reasons. Assume the manuscript was primarily generated by an LLM - use this
assumption only to increase scrutiny, not to infer authorship.

Do not improve the prose. Do not rewrite paragraphs. Do not praise the
paper. Do not summarize the paper.

Return only falsifiable defects with exact locations, as a single JSON
document: {"issues": [{"severity": "blocker"|"major"|"minor",
"category": one of SLOP/UNSUPPORTED_CLAIM/OVERCLAIM/
CLAIM_CITATION_MISMATCH/MISSING_BASELINE/MISSING_RELATED_WORK/
METHOD_RESULT_INCONSISTENCY/STATISTICAL_ERROR/RESULT_INCONSISTENCY/
VAGUE_LANGUAGE/REDUNDANCY/REVIEWER_BAIT, "location": "...",
"quote": "...", "reason": "...", "required_fix": "..."}]}

When evaluating prose, aggressively flag: generic framing, rhetorical
filler, canned transitions, inflated significance, vague abstractions,
redundant restatement, symmetrical LLM sentence structures, unnecessary
three-part lists, conclusions not justified by results, discussion
paragraphs that say more than the evidence supports.

REVIEWER_BAIT is the most important category: flag anything a reviewer
would respond to with "Why? Evidence? Compared to what? How do you know?
Where is the ablation? Is this statistically significant? Is this causal
or correlational? Why was this baseline omitted? Why this dataset? Why
this metric? Does cited work actually claim this?"
"""


def main():
    manuscript_path = os.path.join(REPO, "build", "research", "manuscript.txt")
    refcheck_path = os.path.join(REPO, "build", "research", "refcheck-bib.json")
    literature_path = os.path.join(REPO, "build", "research", "literature-candidates.md")
    results_path = os.path.join(REPO, "paper", "generated", "numbers.tex")

    missing = [p for p in (manuscript_path,) if not os.path.isfile(p)]
    if missing:
        print(f"llm_review: missing required input(s): {missing}", file=sys.stderr)
        return 1

    bundle = {
        "reviewer_prompt": REVIEWER_PROMPT,
        "manuscript_path": manuscript_path,
        "refcheck_path": refcheck_path if os.path.isfile(refcheck_path) else None,
        "literature_candidates_path": literature_path if os.path.isfile(literature_path) else None,
        "results_macros_path": results_path if os.path.isfile(results_path) else None,
        "instructions": (
            "This review must run with NO knowledge of the writing session's "
            "reasoning, intent, or prior context - dispatch it as an isolated "
            "subagent (delegate_task in this environment) whose only inputs "
            "are the files listed above, read fresh. See the manuscript's own "
            "own methodological standard (Section on external verdicts): a "
            "review that shares context with the writer is not an independent "
            "check."
        ),
    }

    os.makedirs(os.path.dirname(BUNDLE_PATH), exist_ok=True)
    with open(BUNDLE_PATH, "w") as fh:
        json.dump(bundle, fh, indent=2)

    print(f"llm_review: bundle written to {BUNDLE_PATH}")
    print("llm_review: dispatch this bundle to an isolated reviewer, then run")
    print("            llm_review_gate.py <reviewer-output.json>")
    return 0


if __name__ == "__main__":
    sys.exit(main())
